/**
 * 安装 Kongming Node Git 检查钩子，保留 Git LFS 和其他现有钩子。
 * installHooks 读取 Git 的钩子目录、核对现有钩子来源、保存旧钩子备份，
 * 再复制受版本控制的 pre-commit/pre-push 并设置执行权限。
 */
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** 安装已识别的钩子；原内容备份至 .kmh，未知钩子立即报错并保留。 */
function installHooks() {
  const git = spawnSync('git', ['rev-parse', '--git-path', 'hooks'], { cwd: root, encoding: 'utf8' });
  if (git.error) throw git.error;
  if (git.status !== 0) throw new Error(git.stderr.trim());
  const directory = resolve(root, git.stdout.trim());
  const hooks = ['pre-commit', 'pre-push'].map(name => {
    const source = join(root, '.githooks', name);
    const destination = join(directory, name);
    const content = readFileSync(source, 'utf8');
    const previous = existsSync(destination) ? readFileSync(destination, 'utf8') : undefined;
    if (previous !== undefined && previous !== content && !previous.includes('# File generated by pre-commit: https://pre-commit.com')) {
      throw new Error(`发现自定义钩子，请保留后单独合并：${destination}`);
    }
    return { name, source, destination, content, previous };
  });
  const changing = hooks.filter(hook => hook.previous !== hook.content);
  if (!changing.length) { console.log('Kongming Node Git 钩子已安装'); return; }
  const backup = join(root, '.kmh/migration-backups', `python-hooks-${Date.now()}`);
  mkdirSync(backup, { recursive: true });
  for (const hook of changing) {
    if (hook.previous !== undefined) copyFileSync(hook.destination, join(backup, hook.name));
  }
  mkdirSync(directory, { recursive: true });
  for (const hook of changing) { copyFileSync(hook.source, hook.destination); chmodSync(hook.destination, 0o755); }
  console.log(`已安装 Kongming Node Git 钩子；原钩子备份：${backup}`);
}

try { installHooks(); } catch (error) { console.error(`Git 钩子：${error.message}`); process.exitCode = 1; }
